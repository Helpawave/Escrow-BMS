export const INDIAN_STATES = Object.keys(INDIAN_STATES_CITIES).sort();

/**
 * Returns cities for a given state name (with case-insensitive & alias fallback).
 */
export function getCitiesForState(stateName: string): string[] {
  if (!stateName) return [];
  const trimmed = stateName.trim();
  
  // Direct match
  if (INDIAN_STATES_CITIES[trimmed]) {
    return INDIAN_STATES_CITIES[trimmed];
  }

  // Case-insensitive match
  const lower = trimmed.toLowerCase();
  for (const [state, cities] of Object.entries(INDIAN_STATES_CITIES)) {
    if (state.toLowerCase() === lower) {
      return cities;
    }
  }

  // Common aliases
  if (lower.includes("delhi")) return INDIAN_STATES_CITIES["Delhi"] || [];
  if (lower.includes("gujarat")) return INDIAN_STATES_CITIES["Gujarat"] || [];
  if (lower.includes("maharashtra")) return INDIAN_STATES_CITIES["Maharashtra"] || [];
  if (lower.includes("kashmir") || lower.includes("jammu")) return INDIAN_STATES_CITIES["Jammu & Kashmir"] || [];
  if (lower.includes("daman") || lower.includes("diu") || lower.includes("dadra") || lower.includes("silvassa")) {
    return INDIAN_STATES_CITIES["Dadra & Nagar Haveli and Daman & Diu"] || [];
  }
  if (lower.includes("bengal")) return INDIAN_STATES_CITIES["West Bengal"] || [];
  if (lower.includes("uttar pradesh") || lower === "up") return INDIAN_STATES_CITIES["Uttar Pradesh"] || [];
  if (lower.includes("madhya pradesh") || lower === "mp") return INDIAN_STATES_CITIES["Madhya Pradesh"] || [];
  if (lower.includes("andhra")) return INDIAN_STATES_CITIES["Andhra Pradesh"] || [];
  if (lower.includes("tamil")) return INDIAN_STATES_CITIES["Tamil Nadu"] || [];

  return [];
}

/**
 * Normalizes state name to the canonical key in INDIAN_STATES_CITIES
 */
export function normalizeStateName(stateName: string): string {
  if (!stateName) return "";
  const trimmed = stateName.trim();
  if (INDIAN_STATES_CITIES[trimmed]) return trimmed;

  const lower = trimmed.toLowerCase();
  for (const state of Object.keys(INDIAN_STATES_CITIES)) {
    if (state.toLowerCase() === lower) return state;
  }

  if (lower.includes("delhi")) return "Delhi";
  if (lower.includes("gujarat")) return "Gujarat";
  if (lower.includes("maharashtra")) return "Maharashtra";
  if (lower.includes("kashmir") || lower.includes("jammu")) return "Jammu & Kashmir";
  if (lower.includes("daman") || lower.includes("diu") || lower.includes("dadra") || lower.includes("silvassa")) {
    return "Dadra & Nagar Haveli and Daman & Diu";
  }
  if (lower.includes("bengal")) return "West Bengal";
  if (lower.includes("uttar pradesh") || lower === "up") return "Uttar Pradesh";
  if (lower.includes("madhya pradesh") || lower === "mp") return "Madhya Pradesh";
  if (lower.includes("andhra")) return "Andhra Pradesh";
  if (lower.includes("tamil")) return "Tamil Nadu";

  return trimmed;
}

