/**
 * Searches for a matching food/drink image by product name.
 * 1. Checks exact phrase match in 220+ curated cafe dictionary (0ms).
 * 2. Checks multi-word phrase matches.
 * 3. Individual token search in curated dictionary.
 * 4. Keyword heuristic fallbacks.
 * 5. Default gourmet cafe platter photo.
 * Always returns a clean, guaranteed HTTPS URL (never rate-limited third-party AI).
 */
export async function fetchFoodImageByProductName(productName: string): Promise<string> {
  const cleanName = productName.trim().toLowerCase();
  if (!cleanName) return '';

  // 1. Direct match in dictionary (0ms)
  if (CURATED_CAFE_IMAGES[cleanName]) {
    return CURATED_CAFE_IMAGES[cleanName];
  }

  // 2. Multi-word phrase matches (word-boundary safe)
  const matchedPhrase = findCuratedPhrase(cleanName);
  if (matchedPhrase && CURATED_CAFE_IMAGES[matchedPhrase]) {
    return CURATED_CAFE_IMAGES[matchedPhrase];
  }

  // 3. Individual token search in curated dictionary
  const words = cleanName.split(/[\s,+/_-]+/);
  for (const word of words) {
    if (word.length >= 3 && CURATED_CAFE_IMAGES[word]) {
      return CURATED_CAFE_IMAGES[word];
    }
  }

  // 4. Keyword heuristic fallbacks (100% reliable)
  const fallback = getKeywordFallback(cleanName);
  if (fallback) {
    return fallback;
  }

  // 5. If not a recognized food/cafe item, return empty string so non-cafe/IT items never get a salad photo
  return '';
}

/**
 * Extracts image URL embedded in product description [IMG:url]
 */
export function extractProductImage(product?: { description?: string | null; name?: string; image_url?: string }): string | undefined {
  if (product?.image_url && !product.image_url.startsWith('data:')) return product.image_url;
  if (!product?.description) return undefined;
  const match = product.description.match(/\[IMG:(https?:\/\/[^\]]+)\]/);
  return match ? match[1] : undefined;
}

/**
 * Strips [IMG:...] metadata tag from description for clean display
 */
export function cleanProductDescription(description?: string | null): string {
  if (!description) return '';
  return description.replace(/\[IMG:(https?:\/\/[^\]]+)\]\n?/, '').trim();
}

/**
 * Encodes image URL into description. Only actual HTTP/HTTPS links are stored;
 * raw SVG data URIs (data:image/svg+xml...) are never saved to database.
 */
export function encodeProductDescription(description: string, imageUrl?: string): string {
  const clean = cleanProductDescription(description);
  if (!imageUrl || imageUrl.startsWith('data:')) return clean;
  return `[IMG:${imageUrl}]\n${clean}`.trim();
}

