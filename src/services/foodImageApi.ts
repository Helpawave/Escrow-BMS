// Hoisted sorted phrases ordered by length descending for ultra-fast matching
const SORTED_PHRASES = Object.keys(CURATED_CAFE_IMAGES).sort((a, b) => b.length - a.length);

function escapeRegex(str: string): string {
  return str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * Searches curated phrases using word boundaries so short keys like "tea" or "roll"
 * do not match unrelated words such as "Steamed" or "Chicken Steak".
 */
function findCuratedPhrase(name: string): string | undefined {
  return SORTED_PHRASES.find(phrase => {
    const rx = new RegExp(`(^|[^a-z0-9])${escapeRegex(phrase)}([^a-z0-9]|$)`, 'i');
    return rx.test(name);
  });
}

